package validate

import (
	"github.com/gogf/gf/v2/frame/g"
	"orange-crm/app/request"
	"orange-crm/global"
)

type GameAnswer struct{}

// ListValidate 开答列表验证
func (v *GameAnswer) ListValidate(req *request.GameAnswerListRequest) error {
	if err := g.Validator().Bail().Data(req).Run(global.I18N.Context); err != nil {
		return err
	}
	return nil
}
